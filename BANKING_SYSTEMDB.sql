-- CUSTOMER ANALYSIS

-- HOW MANY CUSTOMERS ARE THERE ?

SELECT COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS;

-- WHICH CUTOMERS HAVING MISSING INFO 

SELECT * 
FROM CUSTOMERS;

SELECT CUSTOMERID,FIRSTNAME
FROM CUSTOMERS
WHERE LASTNAME IS NULL OR EMAIL IS NULL;

-- WHO ARE THE OLDEST/YOUNGEST CUSTOMERS

SELECT MAX(BIRTHDATE) AS YOUNGEST,MIN(BIRTHDATE) AS OLDEST
FROM CUSTOMERS;

-- HOW MANY CUSTOMERS WERE BORN BEFORE/AFTER
-- BEFORE 2000

SELECT *
FROM CUSTOMERS 
WHERE YEAR(BIRTHDATE)<=2000;

-- AFTER 2000

SELECT * 
FROM CUSTOMERS
WHERE YEAR(BIRTHDATE)>2000;

-- WHICH CUSTOMERS HAVE MULTIPLE ACCOUNTS 

SELECT CUSTOMERID,COUNT(*) AS TOTAL_ACCOUNTS
FROM ACCOUNTS
GROUP BY CUSTOMERID
HAVING TOTAL_ACCOUNTS >1;

-- HOW MANY SAVINGS,CURRENT AND SALARY ACCOUNTS  EXIST ?

SELECT ACCOUNTTYPE,COUNT(*) AS TOTAL_ACCOUNTS
FROM ACCOUNTS
GROUP BY ACCOUNTTYPE;

-- WHAT IS TOTAL BALANCE 

SELECT SUM(BALANCE) AS TOTAL_BALANCE
FROM ACCOUNTS;

-- WHAT IS AVERAGE ACCOUNT BALANCE 

SELECT AVG(BALANCE) AS AVERAGE_BALANCE
FROM ACCOUNTS;

-- WHICH CUSTOMERS HAS THE HIGHEST BALANCE

SELECT CUSTOMERID, BALANCE HIGHEST_BALANCE
FROM ACCOUNTS
ORDER BY BALANCE DESC LIMIT 1;

-- which account has null value ?

SELECT * 
FROM ACCOUNTS 
WHERE BALANCE IS NULL;

-- WHICH BRANCH MANAGE THE MOST ACCOUNT

SELECT BRANCHID,COUNT(*) TOTAL_ACCOUNTS
FROM ACCOUNTS
GROUP BY BRANCHID
ORDER BY TOTAL_ACCOUNTS DESC LIMIT 1;

-- TRANSACTION ANALYSIS
-- WHAT IS TOTAL TRANSACTION AMMOUNT 
 
 SELECT SUM(AMOUNT) AS TOTAL_AMOUNTS
 FROM TRANSACTIONS;
 
 -- HOW MANY DEPOSIT/WITHDRAWS/TRANSFER ARE THERE 
 
 SELECT TRANSCATIONTYPE,COUNT(*) AS TRANSCATION_TYPE
 FROM TRANSACTIONS
 WHERE TRANSCATIONTYPE IN('DEPOSIT','WITHDRAWAL','TRANSFER')
 GROUP BY TRANSCATIONTYPE;

-- WHICH TRANSACTION TYPE HAS HIGHEST VOLUME

SELECT TRANSCATIONTYPE, SUM(AMOUNT) HIGHEST_VOLUME
FROM TRANSACTIONS
GROUP BY TRANSCATIONTYPE
ORDER BY HIGHEST_VOLUME DESC LIMIT 1;

-- WHICH ACCOUNT HAS THE HIGHEST TRANSACTION ACITIVITY

SELECT ACCOUNTID,COUNT(TRANSCATIONID) AS TOTAL_TRANSACTION
FROM TRANSACTIONS
GROUP BY ACCOUNTID 
ORDER BY TOTAL_TRANSACTION DESC LIMIT 1;

-- WHAT IS AVERAGE TRANSACTION AMOUNT 

SELECT AVG(AMOUNT)
FROM TRANSACTIONS;

-- WHICH  TRANSACTIONS HAVE MISSING DATES/AMOUNT?

SELECT *
FROM TRANSACTIONS
WHERE TRANSACTIONDATE IS NULL OR AMOUNT IS NULL;

-- WHAT IS TOTAL LOANS

SELECT CUSTOMERID,SUM(LAONAMOUNT)  TOTAL_LOANS
FROM LOANS
GROUP BY CUSTOMERID
ORDER BY TOTAL_LOANS DESC LIMIT 1;

-- WHICH LOAN HAS THE HIGHEST INTERSET RATE 

SELECT MAX(INTERESTRATE) AS HIGHEST_INTERESTRATE
FROM LOANS;

-- WHICH LOAN IS STILL ACTIVE

SELECT * 
FROM LOANS
WHERE STARTDATE <= now();

